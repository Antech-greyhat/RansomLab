"""Small synthetic in-memory/core-journal assessment, not a VM benchmark."""
from pathlib import Path
import json
import platform
import secrets
import statistics
import sys
import tempfile
import time
from uuid import uuid4

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ransomlab.crypto import encrypt, decrypt, provider_name
from ransomlab.core.events import Event
from ransomlab.core.hashing import hash_bytes
from ransomlab.core.repository import EventStore


def measured(operation, count=5):
    samples = []
    for _ in range(count):
        start = time.perf_counter()
        operation()
        samples.append(time.perf_counter() - start)
    return round(statistics.median(samples), 6)


def main():
    data = b"Generated RansomLab benchmark\n" * 1000
    payload = (data * (1048576 // len(data) + 1))[:1048576]
    key = secrets.token_bytes(32)
    prefix = secrets.token_bytes(4)
    nonces = iter(prefix + index.to_bytes(8, "big") for index in range(5))
    report = {"python": platform.python_version(), "provider": provider_name(), "payload_bytes": len(payload),
              "sha256_median_seconds": measured(lambda: hash_bytes(payload)),
              "encrypt_median_seconds": measured(lambda: encrypt(payload, key, next(nonces), b"synthetic-core-benchmark"))}
    # Use a separate known nonce/ciphertext for decryption timing; encryption
    # never repeats a nonce under the benchmark key.
    decryption_key, decryption_nonce = secrets.token_bytes(32), secrets.token_bytes(12)
    ciphertext = encrypt(payload, decryption_key, decryption_nonce, b"synthetic-core-benchmark")
    report["decrypt_median_seconds"] = measured(lambda: decrypt(ciphertext, decryption_key, decryption_nonce, b"synthetic-core-benchmark"))
    lab_id = str(uuid4())
    with tempfile.TemporaryDirectory(prefix="ransomlab-benchmark-metadata-") as directory:
        with EventStore(Path(directory) / "events.db") as store:
            report["sqlite_append_median_seconds"] = measured(lambda: store.append(Event.create(lab_id, "lab.created", details={"count": 1})), count=20)
    report["scope"] = "Generated bytes in RAM and temporary SQLite metadata only; no filesystem fixture impact or VM performance claim."
    output = ROOT / "output" / "validation"
    output.mkdir(parents=True, exist_ok=True)
    (output / "benchmark.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
